"""Generates the document lab Python parity fixture from synthetic text only.

Usage (needs the legacy requirements): python3 -I scripts/python-parity/document-lab.py . \
  apps/api/test/documents/python-parity.fixture.json  (run from a scratch directory: importing
app.py may create its local data files in the working directory).
"""
import base64, io, json, sys
sys.path.insert(0, sys.argv[1])
import app  # noqa: E402
from docx import Document

themes_text = [
    'La asamblea de la comunidad revisó el mandato de la junta directiva y su vigencia.',
    'Los pobladores presentaron una demanda de empleo local y capacitación para proveedores.',
    'Se firmó un acta con compromiso, responsable y plazo de seguimiento del acuerdo.',
    'Existe una controversia sobre la versión de los hechos; falta verificación de la fuente.',
    'La mesa de diálogo promovió la participación y la facilitación de una reunión.',
    'Hay una oportunidad de desarrollo con inversión en servicios y contratación productiva.',
    'Preocupa el impacto ambiental en el agua, el suelo y la salud del área de influencia.',
    'Elección de representantes: ELECCIÓN anunciada por la Asamblea General de la comunidad!',
    'Corto texto.',
    'Línea con  espacios   múltiples y\ttabulación sobre el reclamo de la comunidad vecina?  Sí.',
]
lines = []
for i in range(14):
    for t in themes_text:
        lines.append(f'{t[:-1]} y registro marcador{chr(97 + i) * 2} anexo{chr(97 + i % 3) * 2}{t[-1]}')
text_a = '﻿' + '\r\n'.join(lines[:40]) + '\n\n' + ' '.join(lines[40:])
def thin(line, i):
    words = line.split()
    # Drop every k-th word so similarities spread below 1.0.
    k = 2 + i % 5
    return ' '.join(w for j, w in enumerate(words) if j % k != 1)
text_b = '\n'.join(thin(l, i) for i, l in enumerate(reversed(lines[5:60])))

def run(text):
    chunks = app.doc_extract(text.encode('utf-8'), 'a.txt')
    items, counts = app.document_insights(chunks)
    return chunks, items, counts

chunks_a, items_a, counts_a = run(text_a)
chunks_b, items_b, counts_b = run(text_b)
rec = [{'tema':k,'accion':app.DOC_ACTIONS[k],'hallazgos_candidatos':v} for k,v in sorted(counts_a.items(),key=lambda p:-p[1])]

# compare logic (same as app.rc21_compare minus I/O)
cands = []
for ia in items_a:
    fa = app._fingerprint(ia['fragmento'])
    if not fa: continue
    for ib in items_b:
        if ia['tema'] != ib['tema']: continue
        fb = app._fingerprint(ib['fragmento']); ov = fa & fb
        if len(ov) < 2: continue
        sim = len(ov)/max(1,len(fa|fb))
        if sim < .11: continue
        cands.append({'tema':ia['tema'],'a':{'ubicacion':ia['ubicacion'],'fragmento':ia['fragmento']},
          'b':{'ubicacion':ib['ubicacion'],'fragmento':ib['fragmento']},'terminos_comunes':sorted(ov)[:10],'coincidencia_lexica':round(sim,2)})
cands.sort(key=lambda x:-x['coincidencia_lexica'])

d = Document()
d.add_paragraph('Acta de reunión & <mesa> de diálogo con la comunidad sobre el acuerdo.')
d.add_paragraph('')
p = d.add_paragraph('Primera parte'); p.add_run('\tsegunda parte del compromiso')
t = d.add_table(rows=3, cols=2)
t.cell(0,0).text = 'Responsable'; t.cell(0,1).text = 'Plazo de seguimiento'
t.cell(2,0).text = 'Demanda de empleo'; t.cell(2,1).text = 'Capacitación'
buf = io.BytesIO(); d.save(buf); blob = buf.getvalue()
docx_chunks = app.doc_extract(blob, 'a.docx')

json.dump({
  'note': 'Generated by scripts/python-parity/document-lab.py from app.py with synthetic text; do not edit by hand.',
  'text_a': text_a, 'text_b': text_b,
  'chunks_a': [{'location':l,'text':x} for l,x in chunks_a],
  'items_a': items_a, 'themes_a': counts_a, 'recommendations_a': rec,
  'items_b': items_b, 'comparisons': cands[:40], 'total_comparisons': len(cands),
  'docx_base64': base64.b64encode(blob).decode(), 'docx_chunks': [{'location':l,'text':x} for l,x in docx_chunks],
}, open(sys.argv[2],'w'), ensure_ascii=False, indent=1)
print(len(chunks_a), len(items_a), counts_a, len(cands), len(docx_chunks))
