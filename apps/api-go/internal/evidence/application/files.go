// The file side of evidence-service.ts: upload, download and the in-app preview. Objects live
// behind ObjectStorage (Cloudflare R2 through its S3 API, or a local directory); metadata,
// the record link and the audit row commit in one tenant transaction (Attacher).

// ObjectStorage is the ObjectStorage port of ports.ts. Keys are generated by the service and
// never derived from user input.
type ObjectStorage interface {
	Put(ctx context.Context, key string, data []byte, contentType string) error
	// Get returns found=false when the object no longer exists.
	Get(ctx context.Context, key string) (data []byte, found bool, err error)
	// Delete is idempotent: deleting a missing object succeeds.
	Delete(ctx context.Context, key string) error
}

// AttachInput is AttachInput of ports.ts: the new metadata row and where it links.
type AttachInput struct {
	ID, StorageKey, OriginalName, ContentType string
	SizeBytes                                 int64
	SHA256                                    string
	LinkedModule, LinkedRecordID              string
	// RecordModule is the stored module name of the linked record (e.g. `Eventos`).
	RecordModule                              string
	DocumentType, Author, Verification, Notes string
	ScopeProjectID                            string
	CreatedAt                                 time.Time
	// LinkDocumentType and LinkVerification are the same values as JavaScript strings for the
	// record's Adjuntos entry (see domain.Link): a cut inside a surrogate pair is kept there.
	LinkDocumentType, LinkVerification js.Text16
}

// Attacher is AttachmentStore.attach: inserts the metadata, appends the link to the record's
// payload and audits it in one tenant transaction; nil when the linked record is not visible
// (nothing is written).
type Attacher interface {
	Attach(ctx context.Context, in AttachInput) (*domain.Attachment, error)
}

// TextExtractor is the TextExtractor port: page texts of an untrusted PDF (tooLong when it has
// more than maxPages pages) and the paragraphs then table rows of a DOCX. An error means the
// bytes are unreadable.
type TextExtractor interface {
	PDF(ctx context.Context, data []byte, maxPages int) (pages []string, tooLong bool, err error)
	DOCX(ctx context.Context, data []byte) ([]string, error)
}

// ErrNoTextExtractor is returned by Preview for a PDF or DOCX when no TextExtractor is wired:
// the TypeScript API reads them with pdf.js and its DOCX reader, which the Go API does not
// port yet.
var ErrNoTextExtractor = errors.New("evidence: no text extractor for this format")

// Files answers uploads, downloads and previews for the request's tenant.
type Files struct {
	Store    Store
	Attacher Attacher
	Storage  ObjectStorage
	// Text reads PDF and DOCX for the preview; nil answers ErrNoTextExtractor.
	Text TextExtractor
	// Now is the clock (milliseconds are kept, as a JavaScript Date).
	Now func() time.Time
	// RandomHex returns n random lower-case hex characters.
	RandomHex      func(n int) (string, error)
	MaxUploadBytes int
}

// UploadInput is UploadInput of evidence-service.ts. A nil metadata field was absent from the
// form (or not text), so its default applies; an empty one stays empty.
type UploadInput struct {
	TenantID, ScopeProjectID     string
	FileName                     string
	Data                         []byte
	LinkedModule, LinkedRecordID string
	DocumentType, Author         *string
	Verification, Notes          *string
}

// UploadError is the kind of a refused upload: the policy's rejections plus `module` and
// `record`; empty when the upload was stored.
type UploadError string

// The UploadError kinds beyond domain.Rejection.
const (
	UploadModule UploadError = "module"
	UploadRecord UploadError = "record"
)

func orDefault(v *string, fallback string) string {
	if v == nil {
		return fallback
	}
	return *v
}

// Upload is evidence.upload. It stores the object first, then commits metadata, record link
// and audit in one transaction; if the record is missing or the transaction fails the object
// is deleted again, so a failed upload leaves neither an orphan file nor a dangling row
// (docs/adr/0008 #9).
func (f Files) Upload(ctx context.Context, in UploadInput) (*domain.Attachment, UploadError, error) {
	moduleSlug := js.LowerJS(js.TrimJS(in.LinkedModule))
	recordModule, ok := records.ModuleForSlug(moduleSlug)
	if !ok {
		return nil, UploadModule, nil
	}
	// A record id PostgreSQL cannot store (NUL, over 200 characters) can never be linked.
	if strings.ContainsRune(in.LinkedRecordID, 0) || js.Len16(in.LinkedRecordID) > records.MaxRecordID {
		return nil, UploadRecord, nil
	}
	accepted, rejection := domain.CheckUpload(in.FileName, in.Data, f.MaxUploadBytes)
	if rejection != "" {
		return nil, UploadError(rejection), nil
	}
	idHex, err := f.RandomHex(12)
	if err != nil {
		return nil, "", err
	}
	keyHex, err := f.RandomHex(32)
	if err != nil {
		return nil, "", err
	}
	key := domain.StorageKey(in.TenantID, keyHex, accepted.SafeName)
	if err := f.Storage.Put(ctx, key, in.Data, accepted.ContentType); err != nil {
		return nil, "", err
	}
	documentType := orDefault(in.DocumentType, domain.DefaultDocumentType)
	verification := orDefault(in.Verification, domain.DefaultVerification)
	sum := sha256.Sum256(in.Data)
	attachment, err := f.Attacher.Attach(ctx, AttachInput{
		ID:             "ADJ-" + strings.ToUpper(idHex),
		StorageKey:     key,
		OriginalName:   accepted.SafeName,
		ContentType:    accepted.ContentType,
		SizeBytes:      int64(len(in.Data)),
		SHA256:         hex.EncodeToString(sum[:]),
		LinkedModule:   moduleSlug,
		LinkedRecordID: in.LinkedRecordID,
		RecordModule:   recordModule,
		DocumentType:   domain.SliceStored(documentType, domain.MaxDocumentType),
		Author:         domain.SliceStored(orDefault(in.Author, ""), domain.MaxAuthor),
		Verification:   domain.SliceStored(verification, domain.MaxVerification),
		Notes:          domain.SliceStored(orDefault(in.Notes, ""), domain.MaxNotes),
		ScopeProjectID: in.ScopeProjectID,
		CreatedAt:      f.now(),
		// The TypeScript store links the sliced JavaScript strings into the payload.
		LinkDocumentType: js.Slice16(documentType, domain.MaxDocumentType),
		LinkVerification: js.Slice16(verification, domain.MaxVerification),
	})
	if err != nil {
		// The cleanup's own failure is not reported: the transaction error is the one that matters.
		_ = f.Storage.Delete(context.WithoutCancel(ctx), key)
		return nil, "", err
	}
	if attachment == nil {
		// Not cancelled with the request, as the TypeScript cleanup never is: no orphan object.
		if err := f.Storage.Delete(context.WithoutCancel(ctx), key); err != nil {
			return nil, "", err
		}
		return nil, UploadRecord, nil
	}
	return attachment, "", nil
}

// now is clock.now() as a JavaScript Date holds it: milliseconds.
func (f Files) now() time.Time {
	now := time.Now
	if f.Now != nil {
		now = f.Now
	}
	return now().Truncate(time.Millisecond)
}

// lookup is `storable(id) && id.length <= 64 ? store.get(tenantId, id) : null`.
func (f Files) lookup(ctx context.Context, id string) (*domain.Attachment, error) {
	if !ValidID(id) {
		return nil, nil
	}
	return f.Store.Get(ctx, id)
}

// Download is evidence.download: the metadata and the bytes, nil metadata when no visible
// attachment has that id, and found=false when its object is gone.
func (f Files) Download(ctx context.Context, id string) (a *domain.Attachment, data []byte, found bool, err error) {
	a, err = f.lookup(ctx, id)
	if err != nil || a == nil {
		return nil, nil, false, err
	}
	data, found, err = f.Storage.Get(ctx, a.StorageKey)
	if err != nil {
		return nil, nil, false, err
	}
	return a, data, found, nil
}

// PreviewKind is the `kind` of a Preview.
type PreviewKind string

// The Preview kinds of evidence-service.ts.
const (
	PreviewMissingMetadata PreviewKind = "missing_metadata"
	PreviewMissingObject   PreviewKind = "missing_object"
	PreviewText            PreviewKind = "text"
	PreviewImage           PreviewKind = "image"
	PreviewNoText          PreviewKind = "no_text"
	PreviewTooLong         PreviewKind = "too_long"
	PreviewUnsupported     PreviewKind = "unsupported"
)

// Preview is Preview of evidence-service.ts.
type Preview struct {
	Kind       PreviewKind
	Attachment *domain.Attachment
	Format     domain.PreviewFormat
	Pages      []js.Text16
	Truncated  bool
}

// Preview is evidence.preview: what the in-app viewer shows of a stored file (functional
// audit, error 05).
func (f Files) Preview(ctx context.Context, id string) (Preview, error) {
	a, err := f.lookup(ctx, id)
	if err != nil {
		return Preview{}, err
	}
	if a == nil {
		return Preview{Kind: PreviewMissingMetadata}, nil
	}
	image, format := domain.PreviewTarget(a.OriginalName)
	switch {
	case image:
		return Preview{Kind: PreviewImage, Attachment: a}, nil
	case format == "":
		return Preview{Kind: PreviewUnsupported, Attachment: a}, nil
	}
	data, found, err := f.Storage.Get(ctx, a.StorageKey)
	if err != nil {
		return Preview{}, err
	}
	if !found {
		return Preview{Kind: PreviewMissingObject, Attachment: a}, nil
	}
	var pages []string
	switch format {
	case domain.FormatTXT, domain.FormatCSV:
		pages = []string{domain.PlainText(data)}
	default:
		if f.Text == nil {
			return Preview{}, ErrNoTextExtractor
		}
		var tooLong bool
		if format == domain.FormatPDF {
			pages, tooLong, err = f.Text.PDF(ctx, data, domain.PreviewMaxPages)
		} else {
			var paragraphs []string
			paragraphs, err = f.Text.DOCX(ctx, data)
			pages = []string{strings.Join(paragraphs, "\n")}
		}
		if err != nil {
			return Preview{Kind: PreviewNoText, Attachment: a}, nil //nolint:nilerr // unreadable bytes are a kind, not a failure
		}
		if tooLong {
			return Preview{Kind: PreviewTooLong, Attachment: a}, nil
		}
	}
	if !domain.HasText(pages) {
		return Preview{Kind: PreviewNoText, Attachment: a}, nil
	}
	clipped, truncated := domain.Clip(pages)
	return Preview{Kind: PreviewText, Attachment: a, Format: format, Pages: clipped, Truncated: truncated}, nil
}
