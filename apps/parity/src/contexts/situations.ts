/**
 * Synthetic records and settings of the situations routes (GET /system/v4/settings and
 * /system/v4/situations) in DEFAULT_TENANT and OTHER_TENANT (see ../fixtures.ts). Dates count back
 * from today in Lima, as both APIs do, so the records fall in the project's window on any run
 * day. The default project gets saved settings, a rising topic, actors, territories, narratives
 * whose tone turns negative, lessons, a record marked 'restringido' (hidden from `consulta`), an
 * undated, a future and an out-of-window record, a SIPGES-generated alert, numbers where text is
 * expected (1.50 reads "1.5") and a title cut inside an emoji. OTHER_TENANT's records share the
 * topics and carry "AJENA", so a leak is plain in a mismatch report.
 */

/** A text value, or a SQL expression (dates, numeric literals that keep their scale). */
type Value = string | { readonly sql: string };

/** `YYYY-MM-DD`, `age` days before today in Lima. */
const daysAgo = (age: number) => ({
  sql: `to_char((now() AT TIME ZONE 'America/Lima')::date - ${age}, 'YYYY-MM-DD')`,
});

/** `d/m/yyyy`, the other date format the situations read. */
const localDaysAgo = (age: number): Value => ({
  sql: `to_char((now() AT TIME ZONE 'America/Lima')::date - ${age}, 'FMDD/FMMM/YYYY')`,
});

const literal = (value: Value) =>
  typeof value === 'object' ? value.sql : `'${value.replaceAll("'", "''")}'`;

const record = (
  tenant: string,
  module: string,
  id: string,
  fields: Readonly<Record<string, Value>>,
  marking = 'interno',
) => {
  const pairs = Object.entries(fields).map(([key, value]) => `${literal(key)}, ${literal(value)}`);
  return `('${tenant}', '${module}', '${id}', jsonb_build_object(${pairs.join(', ')}), '${marking}',
    '2026-01-01T00:00:00Z', '2026-01-01T00:00:00Z')`;
};

