export const cases: readonly ParityCase[] = (['settings', 'situations'] as const)
  .flatMap((route): ParityCase[] => {
    const path = `/system/v4/${route}`;
    // generated_at is the time of each answer.
    const normalize = route === 'situations' ? { normalize: ['generated_at'] } : {};
    return [
      { name: `${route}: active project`, method: 'GET', path, auth: 'admin', ...normalize },
      { name: `${route}: read-only role`, method: 'GET', path, auth: 'consulta', ...normalize },
      {
        name: `${route}: second project (no saved settings or records)`,
        method: 'GET',
        path,
        auth: 'multi',
        headers: SECOND,
        ...normalize,
      },
      {
        name: `${route}: default project of a two-project user`,
        method: 'GET',
        path,
        auth: 'multi',
        headers: { 'x-sipges-scope': SECHURA },
        ...normalize,
      },
      { name: `${route}: without a session`, method: 'GET', path },
      { name: `${route}: two projects need a choice`, method: 'GET', path, auth: 'multi' },
      {
        name: `${route}: project without a grant`,
        method: 'GET',
        path,
        auth: 'admin',
        headers: OTHER_SCOPE,
      },
      {
        name: `${route}: query project_id of another project`,
        method: 'GET',
        path: `${path}?project_id=OTRO`,
        auth: 'admin',
      },
      {
        name: `${route}: query project_id of the active project`,
        method: 'GET',
        path: `${path}?project_id=PRJ-SECHURA`,
        auth: 'admin',
        ...normalize,
      },
      { name: `${route}: trailing slash`, method: 'GET', path: `${path}/`, auth: 'admin' },
      { name: `${route}: HEAD`, method: 'HEAD', path, auth: 'admin' },
    ];
  })
  .concat([
    {
      name: 'settings: write refused for the read-only role',
      method: 'PUT',
      path: '/system/v4/settings',
      auth: 'consulta',
      sameOrigin: true,
      body: { json: { window_days: 30 } },
    },
    ...settingsWrites,
  ]);
