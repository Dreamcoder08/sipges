/**
 * Synthetic records and settings for the situations routes (GET /system/v4/settings and
 * /system/v4/situations), created through the TypeScript API. Dates count back from today in
 * Lima, so both APIs place them in the same window. The default project gets saved settings, a
 * rising topic, actors, territories, narratives whose tone turns negative, a lesson and an
 * undated record; the second project gets other records with the same topics, so a read of one
 * project that showed the other's would differ.
 */

type Send = (path: string, body: unknown) => Promise<unknown>;

const DAY_MS = 86_400_000;
const LIMA_DAY = new Intl.DateTimeFormat('en-CA', { timeZone: 'America/Lima' });

const send =
  (
    method: 'POST' | 'PUT',
    tsUrl: string,
    cookie: string,
    headers: Readonly<Record<string, string>>,
  ): Send =>
  async (path, body) => {
    const response = await fetch(`${tsUrl}${path}`, {
      method,
      headers: { 'content-type': 'application/json', origin: tsUrl, cookie, ...headers },
      body: JSON.stringify(body),
      signal: AbortSignal.timeout(15_000),
    });
    if (!response.ok) {
      throw new Error(`seed ${path} failed with ${response.status}: ${await response.text()}`);
    }
    return response.json();
  };

/** `YYYY-MM-DD` `age` days before today in Lima. */
const daysAgo = (age: number) => {
  const today = LIMA_DAY.format(new Date());
  return new Date(Date.parse(`${today}T00:00:00Z`) - age * DAY_MS).toISOString().slice(0, 10);
};

/** `d/m/yyyy`, the other date format the situations read. */
const localDaysAgo = (age: number) => {
  const [y, m, d] = daysAgo(age).split('-').map(Number);
  return `${d}/${m}/${y}`;
};

