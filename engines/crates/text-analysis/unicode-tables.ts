/**
 * Generates `src/unicode_tables.rs`: the code-point ranges of the general categories the
 * TypeScript engine matches with Unicode regular expressions (`/\p{Mn}/u` in `foldMarks`,
 * `[\p{L}\p{N}_]` in `hasWholeWord`), read from the same V8/ICU that runs the API, so the Rust
 * engine classifies every code point exactly as JavaScript does.
 *
 *   node engines/crates/text-analysis/unicode-tables.ts          # rewrite the tables
 *   node engines/crates/text-analysis/unicode-tables.ts --check  # fail when they are stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const TARGET = fileURLToPath(new URL('./src/unicode_tables.rs', import.meta.url));

const ranges = (re: RegExp): [number, number][] => {
  const out: [number, number][] = [];
  for (let cp = 0; cp <= 0x10ffff; cp += 1) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue; // not a Rust `char`
    if (!re.test(String.fromCodePoint(cp))) continue;
    const last = out[out.length - 1];
    if (last && last[1] === cp - 1) last[1] = cp;
    else if (last && last[1] === 0xd7ff && cp === 0xe000) last[1] = cp;
    else out.push([cp, cp]);
  }
  return out;
};

const hex = (n: number) => `0x${n.toString(16).toUpperCase().padStart(4, '0')}`;

const table = (name: string, doc: string, re: RegExp) => {
  const rs = ranges(re);
  const rows = rs.map(([a, b]) => `    (${hex(a)}, ${hex(b)}),`).join('\n');
  return `/// ${doc}\npub const ${name}: [(u32, u32); ${rs.length}] = [\n${rows}\n];\n`;
};

const out = `//! Generated by \`node engines/crates/text-analysis/unicode-tables.ts\` from the JavaScript
//! engine's Unicode ${process.versions.unicode} data; do not edit by hand.
//! Inclusive, sorted, non-overlapping code-point ranges (surrogates excluded).

/// Unicode version of the tables.
pub const UNICODE_VERSION: &str = "${process.versions.unicode}";

${table('MN', '\`/\\p{Mn}/u\`: nonspacing marks.', /^\p{Mn}$/u)}
${table('L', '\`/\\p{L}/u\`: letters.', /^\p{L}$/u)}
${table('N', '\`/\\p{N}/u\`: numbers.', /^\p{N}$/u)}`;

if (process.argv.includes('--check')) {
  if (readFileSync(TARGET, 'utf8') !== out) {
    console.error(`Stale tables: ${TARGET}. Run node engines/crates/text-analysis/unicode-tables.ts`);
    process.exit(1);
  }
  console.log('Unicode tables are current.');
} else {
  writeFileSync(TARGET, out);
  console.log(`Wrote ${TARGET}`);
}
